// Writes src/face/text-widths.ts: the advance width of each character, in units of the font size,
// read from the Arial Bold font file of this computer. Run it again only when the character list changes.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const USAGE = [
  "Usage: node scripts/make-text-widths.mjs <Arial Bold font file>",
  "  WSL:   /mnt/c/Windows/Fonts/arialbd.ttf",
  '  macOS: "/System/Library/Fonts/Supplemental/Arial Bold.ttf"',
].join("\n");
const OUTPUT_FILE = new URL("../src/face/text-widths.ts", import.meta.url);
const EXTRA_CHARACTERS = "…–—‘’“”•";

function characterList() {
  const characters = [];
  for (let code = 0x20; code <= 0x7e; code++) characters.push(String.fromCharCode(code));
  for (let code = 0xa0; code <= 0xff; code++) characters.push(String.fromCharCode(code));
  return [...characters, ...EXTRA_CHARACTERS];
}

function tableOffsets(font) {
  const tableCount = font.readUInt16BE(4);
  const offsets = {};
  for (let index = 0; index < tableCount; index++) {
    const record = 12 + index * 16;
    offsets[font.toString("latin1", record, record + 4)] = font.readUInt32BE(record + 8);
  }
  return offsets;
}

// The glyph id of each character, from the cmap subtable of format 4 (Unicode BMP).
function glyphIdReader(font, cmapOffset) {
  const subtableCount = font.readUInt16BE(cmapOffset + 2);
  for (let index = 0; index < subtableCount; index++) {
    const record = cmapOffset + 4 + index * 8;
    const subtable = cmapOffset + font.readUInt32BE(record + 4);
    if (font.readUInt16BE(subtable) !== 4) continue;
    const segmentCount = font.readUInt16BE(subtable + 6) / 2;
    const endCodes = subtable + 14;
    const startCodes = endCodes + segmentCount * 2 + 2;
    const deltas = startCodes + segmentCount * 2;
    const rangeOffsets = deltas + segmentCount * 2;
    return (code) => {
      for (let segment = 0; segment < segmentCount; segment++) {
        if (code > font.readUInt16BE(endCodes + segment * 2)) continue;
        const start = font.readUInt16BE(startCodes + segment * 2);
        if (code < start) return 0;
        const delta = font.readUInt16BE(deltas + segment * 2);
        const rangeOffsetPosition = rangeOffsets + segment * 2;
        const rangeOffset = font.readUInt16BE(rangeOffsetPosition);
        if (rangeOffset === 0) return (code + delta) & 0xffff;
        const glyph = font.readUInt16BE(rangeOffsetPosition + rangeOffset + (code - start) * 2);
        return glyph === 0 ? 0 : (glyph + delta) & 0xffff;
      }
      return 0;
    };
  }
  throw new Error("The font has no cmap subtable of format 4");
}

function readWidths(fontFile) {
  const font = readFileSync(fontFile);
  const offsets = tableOffsets(font);
  const unitsPerEm = font.readUInt16BE(offsets.head + 18);
  const metricCount = font.readUInt16BE(offsets.hhea + 34);
  const glyphId = glyphIdReader(font, offsets.cmap);
  const advance = (glyph) => font.readUInt16BE(offsets.hmtx + Math.min(glyph, metricCount - 1) * 4);
  const widths = {};
  for (const character of characterList()) {
    const glyph = glyphId(character.codePointAt(0));
    if (glyph !== 0) widths[character] = Math.round((advance(glyph) / unitsPerEm) * 10000) / 10000;
  }
  return widths;
}

const fontFile = process.argv[2];
if (!fontFile || !existsSync(fontFile)) {
  console.error(USAGE);
  process.exit(1);
}

writeFileSync(
  OUTPUT_FILE,
  [
    "// Generated by scripts/make-text-widths.mjs from Arial Bold. Do not edit.",
    `export const TEXT_WIDTHS: Record<string, number> = ${JSON.stringify(readWidths(fontFile))};`,
    "",
  ].join("\n"),
);
